#!/usr/bin/env python3
"""Build js/mp-map.js (projected, simplified SVG paths for MP districts).

Source boundaries: udit-001/india-maps-data, geojson/states/madhya-pradesh.geojson
(52 districts). Districts formed in 2023 (Maihar, Mauganj, Pandhurna) are not in
that source; they are added as headquarters markers inside their parent district.

Usage: python3 tools/build_map.py <madhya-pradesh.geojson>
"""
import json
import math
import os
import sys

WIDTH = 1000.0
TOLERANCE = 0.7  # px, Douglas-Peucker simplification in projected space

# District HQ coordinates (lon, lat) for districts missing from the boundary source.
NEW_DISTRICTS = [
    {"name": "Maihar", "parent": "Satna", "lon": 80.7614, "lat": 24.2662, "formed": "2023"},
    {"name": "Mauganj", "parent": "Rewa", "lon": 81.8768, "lat": 24.6800, "formed": "2023"},
    {"name": "Pandhurna", "parent": "Chhindwara", "lon": 78.5230, "lat": 21.5960, "formed": "2023"},
]
RENAMES = {"Hoshangabad": "Narmadapuram", "Agar Malwa": "Agar-Malwa"}


def rings_of(geom):
    if geom["type"] == "Polygon":
        return [geom["coordinates"]]
    if geom["type"] == "MultiPolygon":
        return geom["coordinates"]
    return []


def rdp(points, eps):
    if len(points) < 4:
        return points
    stack = [(0, len(points) - 1)]
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    while stack:
        s, e = stack.pop()
        (x1, y1), (x2, y2) = points[s], points[e]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy) or 1e-12
        best, idx = 0.0, -1
        for i in range(s + 1, e):
            x0, y0 = points[i]
            d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm if (dx or dy) else math.hypot(x0 - x1, y0 - y1)
            if d > best:
                best, idx = d, i
        if best > eps and idx > 0:
            keep[idx] = True
            stack += [(s, idx), (idx, e)]
    return [p for p, k in zip(points, keep) if k]


def area_centroid(ring):
    a = cx = cy = 0.0
    for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1]):
        f = x0 * y1 - x1 * y0
        a += f
        cx += (x0 + x1) * f
        cy += (y0 + y1) * f
    a *= 0.5
    if abs(a) < 1e-9:
        return sum(p[0] for p in ring) / len(ring), sum(p[1] for p in ring) / len(ring), 0
    return cx / (6 * a), cy / (6 * a), abs(a)


def main(src):
    gj = json.load(open(src))
    feats = gj["features"]
    lons = [c[0] for f in feats for poly in rings_of(f["geometry"]) for r in poly for c in r]
    lats = [c[1] for f in feats for poly in rings_of(f["geometry"]) for r in poly for c in r]
    lat0 = (min(lats) + max(lats)) / 2
    kx = math.cos(math.radians(lat0))
    minx, maxx = min(lons) * kx, max(lons) * kx
    s = WIDTH / (maxx - minx)
    height = (max(lats) - min(lats)) * s

    def proj(lon, lat):
        return ((lon * kx - minx) * s, (max(lats) - lat) * s)

    out = []
    for f in feats:
        name = f["properties"]["district"].strip()
        name = RENAMES.get(name, name)
        parts, best = [], (0, 0, -1)
        for poly in rings_of(f["geometry"]):
            for ri, ring in enumerate(poly):
                pts = [proj(*c[:2]) for c in ring]
                if pts[0] == pts[-1]:
                    pts = pts[:-1]
                simp = rdp(pts + [pts[0]], TOLERANCE)[:-1]
                if len(simp) < 3:
                    continue
                parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in simp) + "Z")
                if ri == 0:
                    c = area_centroid(simp)
                    if c[2] > best[2]:
                        best = c
        out.append({"name": name, "d": "".join(parts), "cx": round(best[0], 1), "cy": round(best[1], 1)})

    points = []
    for nd in NEW_DISTRICTS:
        x, y = proj(nd["lon"], nd["lat"])
        points.append({"name": nd["name"], "parent": nd["parent"], "formed": nd["formed"], "cx": round(x, 1), "cy": round(y, 1)})

    data = {"width": WIDTH, "height": round(height, 1), "districts": sorted(out, key=lambda o: o["name"]), "points": points,
            "source": "District boundaries: udit-001/india-maps-data (52 districts). Maihar, Mauganj and Pandhurna (formed 2023) shown at their headquarters."}
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "js", "mp-map.js")
    with open(dest, "w") as fh:
        fh.write("/* Generated by tools/build_map.py - do not edit by hand. */\nwindow.MP_MAP = ")
        json.dump(data, fh, separators=(",", ":"))
        fh.write(";\n")
    print(f"{len(out)} polygons, {len(points)} points, {os.path.getsize(dest) // 1024} KB -> {dest}")


if __name__ == "__main__":
    main(sys.argv[1])
